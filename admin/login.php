<?php
// Start session and load config
require_once __DIR__ . '/../config/config.php';

if (session_status() === PHP_SESSION_NONE) {
    session_start();
}

// If already logged in, redirect to dashboard
if (isset($_SESSION['admin_logged_in']) && $_SESSION['admin_logged_in'] === true) {
    header('Location: dashboard.php');
    exit();
}

$error = '';
$success = '';

// Handle login form submission
if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $username = trim($_POST['username'] ?? '');
    $password = $_POST['password'] ?? '';
    
    // Validate input
    $errors = validateRequired(['username' => $username, 'password' => $password], ['username', 'password']);
    
    if (!empty($errors)) {
        $error = 'Please enter both username and password';
    } else {
        // Use secure credential verification
        $loginResult = verifyAdminLogin($username, $password);
        
        if ($loginResult['success']) {
            $_SESSION['admin_logged_in'] = true;
            $_SESSION['admin_username'] = $loginResult['user']['username'];
            $_SESSION['admin_email'] = $loginResult['user']['email'];
            $_SESSION['admin_login_time'] = time();
            $_SESSION['csrf_token'] = bin2hex(random_bytes(32));
            
            header('Location: dashboard.php');
            exit();
        } else {
            $error = 'Invalid username or password';
        }
    }
}
